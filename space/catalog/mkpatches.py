#!/usr/bin/env python3
"""Build the GeoSpace patch table (VLIR record 20) from pairs of original
and patched CVT files.

usage: mkpatches.py <out.bin|out.inc> ["<GEOS name>" original.cvt patched.cvt] ...
                    [--info "<GEOS name>" "<text>"] ...

--info only appends <text> to the info text (e.g. " @4D18": GEOS65 takes
the serial number from it); no file contents are checked or changed.

For every pair the differing byte runs of all VLIR records become patch
operations (record, offset, original bytes, new bytes); a changed info
text must be the original text plus an appendix and becomes an
'append to info text' operation. GeoSpace checks all original bytes on
the target disk before it writes anything.

Table format (patches.inc, included by patch.s):
  entry:  GEOS file name, 0
          ops: $01 rec off.lo off.hi len old[len] new[len]
               $02 text 0          (append to the info text)
               $00                 (end of entry)
  end:    $00
"""
import sys

def vlir_records(d):
    if d[21] == 0:                      # sequential GEOS file: one data chain
        return [d[508:]]
    assert d[21] == 1, 'unknown file structure'
    t = d[508:762]; pos = 762; recs = []
    for i in range(127):
        b, l = t[2*i], t[2*i+1]
        if b == 0:
            recs.append(None); continue
        size = (b - 1) * 254 + (l - 1)
        recs.append(d[pos:pos+size]); pos += b * 254
    return recs

def info(d):
    o = 254 + 0xA0 - 2
    return bytes(d[o:o+96]).split(b'\0')[0]

def ops_for(orig, new, maxrun=200, gap=4):
    a, b = open(orig, 'rb').read(), open(new, 'rb').read()
    assert len(a) == len(b), 'files must have the same length'
    ra, rb = vlir_records(a), vlir_records(b)
    out = []
    for r, (x, y) in enumerate(zip(ra, rb)):
        if x is None: continue
        assert len(x) == len(y)
        k = 0
        while k < len(x):
            if x[k] == y[k]:
                k += 1; continue
            s = k; e = k
            while e < len(x) and e - s < maxrun:      # merge runs closer than 'gap'
                if x[e] != y[e]:
                    e += 1
                elif any(x[f] != y[f] for f in range(e, min(e + gap, len(x)))):
                    e += 1
                else:
                    break
            out.append(bytes([1, r, s & 255, s >> 8, e - s]) + x[s:e] + y[s:e])
            k = e
    ia, ib = info(a), info(b)
    if ia != ib:
        assert ib.startswith(ia), 'info text change must be an appendix'
        out.append(bytes([2]) + ib[len(ia):] + b'\0')
    return out

def main():
    dst = sys.argv[1]; args = sys.argv[2:]
    specs = []
    while args:
        if args[0] == '--info':
            name, text = args[1], args[2]
            assert text and len(text) < 96
            specs.append((name, [bytes([2]) + text.encode('ascii') + b'\0']))
            args = args[3:]
        else:
            name, orig, new = args[:3]
            specs.append((name, ops_for(orig, new)))
            args = args[3:]
    blob = b''; lines = ['; generated by mkpatches.py - do not edit']
    for name, ops in specs:
        entry = name.encode('ascii') + b'\0' + b''.join(ops) + b'\0'
        lines.append('; %s: %d operations, %d bytes' % (name, len(ops), len(entry)))
        blob += entry
    blob += b'\0'
    for k in range(0, len(blob), 16):
        lines.append('\t.byte\t' + ', '.join('$%02x' % c for c in blob[k:k+16]))
    if dst.endswith('.bin'):        # raw table, e.g. for mkcatalog.py --patches
        open(dst, 'wb').write(blob)
    else:
        open(dst, 'w').write('\n'.join(lines) + '\n')
    print('%s: %d bytes' % (dst, len(blob)))

if __name__ == '__main__':
    main()
