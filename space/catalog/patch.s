;**
;* GeoSpace patch step (VLIR record 3, runs at $6800; the patch table is
;* record 2 of the opened catalog file, loaded to $6C00)
;*
;* Called by the catalog after a successful download and conversion. If
;* the downloaded GEOS file (dlName) has an entry in the patch table, the
;* file on the target drive is patched for GEOS65:
;*   pass 1 checks every original byte, pass 2 writes the new bytes,
;* so nothing is changed if the file is not the expected version.
;* Records are changed block by block with GetBlock/PutBlock along their
;* chain (no ReadFile: GEOS65 runs ReadFile/WriteFile in $5000-$53BC).
;* Out: lastConvertErr = $FD if a patch could not be applied.
;*
;* Table (generated by mkpatches.py, part of the catalog file):
;*   name, 0, ops: $01 rec off.lo off.hi len old[len] new[len]
;*                 $02 text 0 (append to the info text)
;*                 $00 end of entry
;*   $00 end of table
;*

.include "const.inc"
.include "geossym.inc"
.include "geossym2.inc"
.include "geosmac.inc"

.import dlName, targetDrive, appDisk, lastConvertErr
.export PatchStart

patchTable	= $6C00		; patch table of the opened catalog (record 2),
				; loaded by the catalog UI before PatchStart

ptab	= a6			; table pointer
ptabL	= a6L
ptabH	= a6H
pnew	= a7			; new bytes of the current operation
pnewL	= a7L
pnewH	= a7H

INFO_OFFSET	= $A0		; info text in the GEOS file header block
INFO_MAX	= 95

.segment "OVERLAY3"

PatchStart:
	LoadW	ptab, patchTable
@find:	ldy	#0
	lda	(ptab), y
	bne	@cmp
	rts				; no patch for this file
@cmp:	lda	(ptab), y		; compare the entry name with dlName
	cmp	dlName, y
	bne	@skip
	iny
	cmp	#0
	bne	@cmp
	tya
	jsr	addTab			; ptab -> operations
	LoadW	r0, askDialog		; patch available: ask first
	jsr	DoDlgBox
	lda	r0L
	cmp	#YES
	beq	doPatch
	rts
@skip:	jsr	skipStr			; skip name and operations
@sop:	ldy	#0
	lda	(ptab), y
	beq	@next
	cmp	#1
	beq	@op1
	lda	#1			; $02: text
	jsr	addTab
	jsr	skipStr
	jmp	@sop
@op1:	ldy	#4
	lda	(ptab), y		; len
	pha
	lda	#5
	jsr	addTab
	pla
	pha
	jsr	addTab
	pla
	jsr	addTab
	jmp	@sop
@next:	lda	#1
	jsr	addTab
	jmp	@find

; ptab += A
addTab:	clc
	adc	ptabL
	sta	ptabL
	bcc	@1
	inc	ptabH
@1:	rts

; ptab -> behind the zero-terminated string at ptab
skipStr:
	ldy	#0
@1:	lda	(ptab), y
	beq	@2
	iny
	bne	@1
@2:	iny
	tya
	jmp	addTab

;---------------------------------------------------------------------------
doPatch:
	MoveW	ptab, opsStart
	lda	targetDrive
	jsr	SetDevice
	jsr	OpenDisk
	txa
	bne	@fail
	LoadW	r6, dlName
	jsr	FindFile
	txa
	bne	@fail
	lda	dirEntryBuf+21		; VLIR or sequential?
	sta	isVlir
	beq	@seq
	LoadW	r0, dlName
	jsr	OpenRecordFile
	txa
	bne	@fail
@seq:	MoveW	dirEntryBuf+19, hdrTS	; header block of the file
	LoadB	pass, 0
@pass:	MoveW	opsStart, ptab
	LoadB	loaded, 0
	LoadB	dirty, 0
@op:	ldy	#0
	lda	(ptab), y
	beq	@passEnd
	cmp	#1
	beq	@op1
	jsr	opInfo			; $02
	bcs	@failC
	jmp	@op
@op1:	jsr	opBytes
	bcs	@failC
	jmp	@op
@passEnd:
	jsr	flush
	bcs	@failC
	lda	pass
	bne	@done
	inc	pass			; all original bytes found: write
	jmp	@pass
@done:	jsr	closeFile
	jmp	appDisk
@failC:	jsr	closeFile
@fail:	LoadB	lastConvertErr, $FD
	jmp	appDisk

;---------------------------------------------------------------------------
; $01 rec off len old[len] new[len]: check (pass 0) or write (pass 1)
opBytes:
	ldy	#1
	lda	(ptab), y
	sta	opRec
	iny
	lda	(ptab), y
	sta	curOff
	iny
	lda	(ptab), y
	sta	curOff+1
	iny
	lda	(ptab), y
	sta	opLen
	lda	#5
	jsr	addTab			; ptab -> old bytes
	lda	ptabL			; pnew = ptab + len
	clc
	adc	opLen
	sta	pnewL
	lda	ptabH
	adc	#0
	sta	pnewH
	LoadB	opI, 0
@byte:	jsr	ensureBlock		; X = position in diskBlkBuf
	bcs	@err
	ldy	opI
	lda	pass
	bne	@write
	lda	(ptab), y
	cmp	diskBlkBuf, x
	bne	@err			; not the expected version
	jmp	@nextB
@write:	lda	(pnew), y
	sta	diskBlkBuf, x
	LoadB	dirty, 1
@nextB:	IncW	curOff
	inc	opI
	lda	opI
	cmp	opLen
	bne	@byte
	lda	opLen			; ptab -> next operation
	jsr	addTab
	lda	opLen
	jsr	addTab
	clc
	rts
@err:	sec
	rts

; $02 text: append text to the info text (pass 1 only)
opInfo:	lda	pass
	beq	@skip
	jsr	flush
	bcs	@err
	MoveW	hdrTS, r1
	LoadW	r4, diskBlkBuf
	jsr	GetBlock
	txa
	bne	@err
	ldx	#0
@end:	lda	diskBlkBuf+INFO_OFFSET, x
	beq	@app
	inx
	cpx	#INFO_MAX
	bne	@end
	beq	@err
@app:	ldy	#1
@cp:	lda	(ptab), y
	sta	diskBlkBuf+INFO_OFFSET, x
	beq	@put
	iny
	inx
	cpx	#INFO_MAX
	bne	@cp
	beq	@err
@put:	MoveW	hdrTS, r1
	LoadW	r4, diskBlkBuf
	jsr	PutBlock
	txa
	bne	@err
	LoadB	loaded, 0		; diskBlkBuf no longer holds a record block
@skip:	lda	#1
	jsr	addTab
	jsr	skipStr
	clc
	rts
@err:	sec
	rts

;---------------------------------------------------------------------------
; make block (curOff / 254) of record opRec current, X = 2 + curOff % 254
ensureBlock:
	MoveW	curOff, r0
	ldx	#0
@div:	CmpWI	r0, 254
	bcc	@d1
	SubVW	254, r0
	inx
	jmp	@div
@d1:	stx	wantIdx
	lda	r0L
	clc
	adc	#2
	sta	wantPos
	lda	loaded
	beq	@load
	lda	opRec
	cmp	curRec
	bne	@load
	lda	wantIdx
	cmp	curIdx
	beq	@ok
	bcs	@walk			; further on: follow the chain
@load:	jsr	flush			; start at the first block of the record
	bcs	@err
	lda	isVlir
	bne	@vlir
	MoveW	dirEntryBuf+1, curTS	; sequential: the data chain
	jmp	@first
@vlir:	lda	opRec
	asl
	tay
	lda	fileHeader+2, y
	sta	curTS
	lda	fileHeader+3, y
	sta	curTS+1
@first:
	MoveB	opRec, curRec
	LoadB	curIdx, 0
	jsr	readCur
	bcs	@err
	LoadB	loaded, 1
@walk:	lda	curIdx
	cmp	wantIdx
	beq	@ok
	jsr	flush
	bcs	@err
	lda	diskBlkBuf		; next block of the chain
	beq	@err			; record too short
	sta	curTS
	MoveB	diskBlkBuf+1, curTS+1
	inc	curIdx
	jsr	readCur
	bcs	@err
	jmp	@walk
@ok:	ldx	wantPos
	clc
	rts
@err:	sec
	rts

closeFile:
	lda	isVlir
	beq	@r
	jmp	CloseRecordFile
@r:	rts

readCur:
	MoveB	curTS, r1L
	MoveB	curTS+1, r1H
	LoadW	r4, diskBlkBuf
	jsr	GetBlock
	cpx	#1			; carry set on error
	rts

flush:	lda	dirty
	beq	@ok
	MoveB	curTS, r1L
	MoveB	curTS+1, r1H
	LoadW	r4, diskBlkBuf
	jsr	PutBlock
	LoadB	dirty, 0
	cpx	#1
	rts
@ok:	clc
	rts

;---------------------------------------------------------------------------
pass:		.byte	0
loaded:		.byte	0
dirty:		.byte	0
opRec:		.byte	0
opLen:		.byte	0
opI:		.byte	0
curOff:		.word	0
curRec:		.byte	0
curIdx:		.byte	0
curTS:		.word	0
wantIdx:	.byte	0
wantPos:	.byte	0
hdrTS:		.word	0
opsStart:	.word	0
isVlir:		.byte	0

askDialog:
	.byte	$81
	.byte	YES
	.byte	1, 72
	.byte	NO
	.byte	17, 72
	.byte	DBTXTSTR, 10, 16
	.word	txtAsk1
	.byte	DBTXTSTR, 10, 30
	.word	dlName
	.byte	DBTXTSTR, 10, 44
	.word	txtAsk2
	.byte	NULL
txtAsk1:	.byte	BOLDON, "MEGA65 patch available for", PLAINTEXT, NULL
txtAsk2:	.byte	"Apply the patch now?", NULL

